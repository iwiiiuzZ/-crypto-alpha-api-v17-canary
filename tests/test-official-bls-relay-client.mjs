import assert from 'node:assert/strict';
import {collectBlsSources,deliverBlsSources,validOfficialBlSResponse} from '../ops/official-bls-relay.mjs';
const now=Date.parse('2026-10-31T02:00:00Z');
const xml='<rss><channel><item><title>CPI changed</title><link>https://www.bls.gov/news.release/cpi.htm</link><pubDate>Sat, 31 Oct 2026 01:59:00 GMT</pubDate></item></channel></rss>';
const calendar='BEGIN:VCALENDAR\nBEGIN:VEVENT\nSUMMARY:Consumer Price Index\nDTSTART:20261101T120000Z\nEND:VEVENT\nEND:VCALENDAR';
const atom='<feed xmlns="http://www.w3.org/2005/Atom"><entry><title>CPI</title><link href="https://www.bls.gov/news.release/cpi.htm"/><updated>2026-10-31T01:59:00Z</updated></entry></feed>';
assert.equal(validOfficialBlSResponse({url:'https://www.bls.gov/feed/cpi.rss',source:'BLS_CPI',text:atom,contentType:'application/atom+xml; charset=utf-8'}),true);
assert.equal(validOfficialBlSResponse({url:'https://www.bls.gov/feed/cpi.rss',source:'BLS_CPI',text:atom,contentType:'text/html'}),false);
assert.equal(validOfficialBlSResponse({url:'https://www.bls.gov/feed/ppi.rss',source:'BLS_CPI',text:atom,contentType:'application/atom+xml'}),false);
const validFetch=async url=>({ok:true,url,status:200,text:async()=>url.endsWith('.ics')?calendar:xml,headers:{get:()=>null}});
const collected=await collectBlsSources(validFetch,()=>now);
assert.equal(collected.sources.length,4);
assert.equal(collected.failures.length,0);
assert(collected.sources.every(s=>s.fetchedAt==='2026-10-31T02:00:00.000Z'));
let sent=0;
const posted=await deliverBlsSources(async (url,options)=>{sent++;
 assert.equal(options.method,'POST');assert.equal(options.headers.authorization,'Bearer secret');
 const payload=JSON.parse(options.body);assert.equal(payload.sources.length,4);
 return {ok:true,json:async()=>({status:'OFFICIAL_BLS_RELAY_ACCEPTED',accepted:payload.sources.map(x=>x.id)})};
},'https://worker.example','secret',collected);
assert(posted.delivered);assert.equal(sent,1);
assert.equal(validOfficialBlSResponse({url:'https://attacker.example/feed/cpi.rss',text:xml,source:'BLS_CPI'}),false);
assert.equal(validOfficialBlSResponse({url:'http://www.bls.gov/feed/cpi.rss',text:xml,source:'BLS_CPI'}),false);
assert.equal(validOfficialBlSResponse({url:'https://www.bls.gov/feed/cpi.rss',text:'<rss>garbage</rss>',source:'BLS_CPI'}),false);
const spoof=await collectBlsSources(async url=>({ok:true,url:url.replace('www.bls.gov','attacker.example'),text:async()=>xml}),()=>now);
assert.equal(spoof.sources.length,0);assert.equal(spoof.failures.length,4);
const empty=await deliverBlsSources(async()=>{throw new Error('should not post')},'https://worker.example','secret',{sources:[],failures:[]});
assert.equal(empty.delivered,false);
await assert.rejects(()=>deliverBlsSources(validFetch,'https://worker.example',null,collected),/RELAY_AUTH/);
console.log('PASS official BLS relay client validates HTTPS provenance, no proxy spoof, no empty notification and accepted batch');
